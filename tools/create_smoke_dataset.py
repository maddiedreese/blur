#!/usr/bin/env python3
"""Create a deterministic procedural corpus for pipeline smoke tests only."""

from __future__ import annotations

import argparse
import json
import pathlib

import numpy as np
from PIL import Image
from model_pipeline import sha256


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=pathlib.Path)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    rows = []
    specifications = [
        (0, "procedural-real-train", "train", 11),
        (0, "procedural-real-calibration", "calibration", 21),
        (1, "procedural-fake-train", "train", 31),
        (1, "procedural-fake-calibration", "calibration", 41),
        (0, "procedural-real-test", "test", 51),
        (1, "procedural-fake-test", "test", 61),
    ]
    yy, xx = np.indices((448, 512))
    for label, source, split, seed in specifications:
        for variant in range(2):
            rng = np.random.default_rng(seed + variant)
            if label == 0:
                base = rng.normal(127, 35, (448, 512, 3))
                base += 22 * np.sin(xx[..., None] / (17 + variant))
            else:
                base = np.stack([
                    127 + 90 * np.sin((xx + seed) / (7 + variant)),
                    127 + 90 * np.sin((yy + seed * 0.7) / (9 + variant)),
                    127 + 90 * np.sin((xx + yy + seed * 1.3) / (11 + variant)),
                ], axis=2)
            pixels = np.clip(base, 0, 255).astype(np.uint8)
            identifier = f"{source}-{variant}"
            image_path = args.output / f"{identifier}.png"
            Image.fromarray(pixels, mode="RGB").save(image_path)
            rows.append({
                "id": identifier,
                "baseId": identifier,
                "path": image_path.name,
                "sha256": sha256(image_path),
                "label": label,
                "source": source,
                "split": split,
                "license": "CC0-1.0 (procedurally generated by this repository)",
                "originUrl": "https://github.com/maddiedreese/blur",
            })
            if label == 1:
                rows[-1]["generatorFamily"] = source
    manifest = args.output / "manifest.jsonl"
    manifest.write_text("".join(json.dumps(row, separators=(",", ":")) + "\n" for row in rows))
    print(manifest)


if __name__ == "__main__":
    main()
